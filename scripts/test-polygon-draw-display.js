'use strict';
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');

(async () => {
  const dom = new JSDOM('<!doctype html><body></body>', { url: 'http://localhost' });
  global.document = dom.window.document; global.window = dom.window;
  Object.defineProperty(global, 'localStorage', { value: dom.window.localStorage, configurable: true });
  dom.window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  dom.window.HTMLDialogElement.prototype.close = function () { this.open = false; };
  const { PolygonDrawControl } = await import('../assets/map/polygon-draw.js');
  const { drawingCurves } = await import('../assets/map/survey-curve-labels.js');
  const { defaultDrawings } = await import('../assets/map/default-drawings.js');
  const drawings = structuredClone(defaultDrawings);
  const original = JSON.stringify(drawings);
  const key = 'shasta-land-atlas.polygon-drawings.v1', displayKey = 'shasta-land-atlas.polygon-display.v1';
  localStorage.setItem(key, original);
  let data;
  const map = { on() {}, off() {}, getCanvas: () => ({ style: {} }), getSource: () => ({ setData: value => { data = value; } }) };
  const control = new PolygonDrawControl({}); control.onAdd(map); control.refresh();
  const labels = () => data.features.filter(f => f.properties.kind === 'label');
  const vertices = () => data.features.filter(f => f.properties.kind === 'vertex');
  assert.equal(labels().filter(f => f.properties.curveLabel).length, 11, 'shared curves labeled once');
  assert.ok(labels().length < 50, 'hundreds of chord labels removed');
  assert.ok(vertices().length < 80, 'internal curve vertices hidden');
  assert.equal(data.features.filter(f => f.properties.kind === 'edge').length, drawings.reduce((n,d) => n + d.vertices.length, 0));
  const areas = data.features.filter(f => f.properties.kind === 'area');
  for (let i = 0; i < areas.length; i++) assert.deepEqual(areas[i].geometry.coordinates[0], [...drawings[i].vertices, drawings[i].vertices[0]]);
  assert.equal(JSON.stringify(control.drawings), original, 'geometry untouched');
  control.openManager();
  const checkbox = control.manager.querySelector('[data-measurements]');
  assert.equal(checkbox.defaultChecked, true);
  checkbox.checked = false; checkbox.dispatchEvent(new dom.window.Event('change', { bubbles: true }));
  assert.equal(labels().length, 0); assert.ok(data.features.some(f => f.properties.kind === 'area'));
  const restored = new PolygonDrawControl({}); assert.equal(restored.showMeasurements, false);
  control.resetDisplay(); assert.equal(control.showMeasurements, true); assert.equal(localStorage.getItem(displayKey), null);
  const baseVertices = vertices().length;
  control.manager.querySelector('[data-action="edit-curves"][data-id="castle-oaks-survey-parcel-3"]').click();
  assert.ok(vertices().length > baseVertices + 100, 'edit mode reveals chord vertices');
  control.openManager(); control.manager.querySelector('[data-action="edit-curves"][data-id="castle-oaks-survey-parcel-3"]').click();
  assert.equal(vertices().length, baseVertices);
  const edited = structuredClone(drawings[2]); const before = drawingCurves(edited);
  edited.vertices[10][0] += .00001;
  assert.equal(drawingCurves(edited).length, before.length - 1, 'stale survey label invalidated after edit');
  assert.equal(drawingCurves({id:'ordinary',vertices:drawings[2].vertices}).length, 0, 'no guessed curves for arbitrary polygons');
  assert.equal(localStorage.getItem(key), original, 'display preferences never rewrite saved geometry');
  control.onRemove();
  console.log('Passed: grouped curve labels, unchanged geometry, editing, measurements persistence/reset.');
})().catch(error => { console.error(error); process.exit(1); });
