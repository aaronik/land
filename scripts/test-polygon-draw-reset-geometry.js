'use strict';
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');

(async () => {
  const dom = new JSDOM('<!doctype html><body></body>', { url: 'https://example.test' });
  global.document = dom.window.document; global.window = dom.window;
  Object.defineProperty(global, 'localStorage', { value: dom.window.localStorage, configurable: true });
  dom.window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  dom.window.HTMLDialogElement.prototype.close = function () { this.open = false; };
  const { PolygonDrawControl } = await import('../assets/map/polygon-draw.js');
  const { defaultDrawings } = await import('../assets/map/default-drawings.js');
  const { DRAWINGS_KEY } = await import('../assets/map/drawing-seeds.js');
  const originals = structuredClone(defaultDrawings);
  originals[0].vertices[0][0] += .001;
  originals[0].name = 'Renamed polygon'; originals[0].visible = false;
  originals[1].vertices[1][1] += .001;
  originals.push({ id: 'custom', name: 'Custom', visible: true, vertices: [[0, 0], [1, 0], [0, 1]] });
  localStorage.setItem(DRAWINGS_KEY, JSON.stringify(originals));
  let data;
  const map = { on() {}, off() {}, getCanvas: () => ({ style: {} }), getSource: () => ({ setData: value => { data = value; } }) };
  const control = new PolygonDrawControl({}); control.onAdd(map); control.openManager();
  const restore = () => control.manager.querySelector(`[data-action="reset-geometry"][data-id="${originals[0].id}"]`);
  assert(restore(), 'modified default has restore action');
  assert.equal(control.manager.querySelector(`[data-action="reset-geometry"][data-id="custom"]`), null);
  assert.match(control.manager.querySelector('[data-action="reset-display"]').textContent, /measurement/);
  let confirmed = false; window.confirm = () => confirmed;
  restore().click(); assert.deepEqual(control.drawings[0].vertices, originals[0].vertices, 'cancel does not change corners');
  confirmed = true; restore().click();
  assert.deepEqual(control.drawings[0].vertices, defaultDrawings[0].vertices);
  assert.equal(control.drawings[0].name, 'Renamed polygon'); assert.equal(control.drawings[0].visible, false);
  assert.deepEqual(control.drawings[1].vertices, originals[1].vertices, 'other edited default remains untouched');
  assert.deepEqual(control.drawings.at(-1), originals.at(-1), 'custom polygon remains untouched');
  assert.deepEqual(JSON.parse(localStorage.getItem(DRAWINGS_KEY))[0].vertices, defaultDrawings[0].vertices, 'restoration persists');
  assert.equal(restore(), null, 'restore action disappears once corners match');
  assert(data.features.some(feature => feature.properties.drawingId === originals[1].id));
  control.onRemove();
  console.log('Polygon default geometry restoration tests passed');
})().catch(error => { console.error(error); process.exit(1); });
